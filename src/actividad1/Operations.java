package actividad1;

public class Operations {
    public static double sum1(double sum, double x) {
        return sum + x;
    }
    
    public static double calculateX(double x, double y) {
        return x + (Math.pow(y, 2));
    }
    
    public static double sum2(double x, double y, double sum1) {
        return sum1 + (x / y);
    }
}
